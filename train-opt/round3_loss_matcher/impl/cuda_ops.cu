torch::Tensor point_loss_forward_cuda(torch::Tensor pred, torch::Tensor target,
                                      torch::Tensor coords, torch::Tensor bce,
                                      torch::Tensor dice, torch::Tensor sx,
                                      torch::Tensor sy, torch::Tensor num,
                                      torch::Tensor den) {
  const auto stream = at::cuda::getCurrentCUDAStream().stream();
  const int m = pred.size(0), ph = pred.size(1), pw = pred.size(2);
  const int th = target.size(1), tw = target.size(2), p = coords.size(1);
  AT_DISPATCH_FLOATING_TYPES_AND2(at::kHalf, at::kBFloat16, pred.scalar_type(), "point_loss_forward", [&] {
    using target_t = uint8_t;
    point_forward_kernel<scalar_t, target_t><<<m, 256, 0, stream>>>(
        pred.data_ptr<scalar_t>(), target.data_ptr<target_t>(), coords.data_ptr<float>(),
        bce.data_ptr<float>(), dice.data_ptr<float>(), sx.data_ptr<float>(), sy.data_ptr<float>(),
        num.data_ptr<float>(), den.data_ptr<float>(), m, ph, pw, th, tw, p);
  });
  C10_CUDA_KERNEL_LAUNCH_CHECK();
  return bce;
}

torch::Tensor point_loss_backward_cuda(torch::Tensor coords, torch::Tensor sx,
                                       torch::Tensor sy, torch::Tensor num,
                                       torch::Tensor den, torch::Tensor gb,
                                       torch::Tensor gd, torch::Tensor grad) {
  const auto stream = at::cuda::getCurrentCUDAStream().stream();
  const int m = sx.size(0), p = sx.size(1), ph = grad.size(1), pw = grad.size(2);
  // Shared accumulation avoids the four-way global atomic hotspot for the
  // production 128x128 maps (64 KiB per block).  Keep a global atomic
  // fallback for unusually large maps so correctness does not depend on a
  // particular SM shared-memory carveout.
  const int pixels = ph * pw;
  const int max_shared_pixels = 24576;  // 96 KiB, SM120 opt-in limit
  if (pixels <= max_shared_pixels) {
    cudaFuncSetAttribute(point_backward_kernel,
                         cudaFuncAttributeMaxDynamicSharedMemorySize,
                         max_shared_pixels * static_cast<int>(sizeof(float)));
    point_backward_kernel<<<m, 256, pixels * sizeof(float), stream>>>(
        coords.data_ptr<float>(), sx.data_ptr<float>(), sy.data_ptr<float>(),
        num.data_ptr<float>(), den.data_ptr<float>(), gb.data_ptr<float>(),
        gd.data_ptr<float>(), grad.data_ptr<float>(), m, ph, pw, p);
  } else {
    point_backward_global_kernel<<<m, 256, 0, stream>>>(
        coords.data_ptr<float>(), sx.data_ptr<float>(), sy.data_ptr<float>(),
        num.data_ptr<float>(), den.data_ptr<float>(), gb.data_ptr<float>(),
        gd.data_ptr<float>(), grad.data_ptr<float>(), m, ph, pw, p);
  }
  C10_CUDA_KERNEL_LAUNCH_CHECK();
  return grad;
}

torch::Tensor matcher_exact_cuda(torch::Tensor cost, torch::Tensor valid) {
  auto out = torch::full({cost.size(0), cost.size(2)}, -1, cost.options().dtype(torch::kInt64));
  const auto stream = at::cuda::getCurrentCUDAStream().stream();
  matcher_kernel<<<cost.size(0), 32, 0, stream>>>(cost.data_ptr<float>(), valid.data_ptr<bool>(), out.data_ptr<int64_t>(), cost.size(0), cost.size(1), cost.size(2));
  C10_CUDA_KERNEL_LAUNCH_CHECK();
  return out;
}
