template <typename scalar_t>
__device__ __forceinline__ float load_value(const scalar_t* p) {
  return static_cast<float>(*p);
}
template <>
__device__ __forceinline__ float load_value<at::Half>(const at::Half* p) {
  return __half2float(*reinterpret_cast<const __half*>(p));
}
template <>
__device__ __forceinline__ float load_value<at::BFloat16>(const at::BFloat16* p) {
  return __bfloat162float(*reinterpret_cast<const __nv_bfloat16*>(p));
}

template <typename scalar_t>
__device__ __forceinline__ float bilinear(const scalar_t* base, int h, int w, float px, float py) {
  // Matches grid_sample(align_corners=False), including the zero padding at
  // coordinates outside the image.
  const float fx = px * w - 0.5f;
  const float fy = py * h - 0.5f;
  const int x0 = floorf(fx), y0 = floorf(fy);
  const int x1 = x0 + 1, y1 = y0 + 1;
  const float dx = fx - x0, dy = fy - y0;
  // Keep the four bounds checks independent.  This lets ptxas schedule the
  // address arithmetic around the random texture-like loads and avoids the
  // device lambda generated by the original reference implementation.
  const float a = (x0 >= 0 && x0 < w && y0 >= 0 && y0 < h) ? load_value(base + y0 * w + x0) : 0.f;
  const float b = (x1 >= 0 && x1 < w && y0 >= 0 && y0 < h) ? load_value(base + y0 * w + x1) : 0.f;
  const float c = (x0 >= 0 && x0 < w && y1 >= 0 && y1 < h) ? load_value(base + y1 * w + x0) : 0.f;
  const float d = (x1 >= 0 && x1 < w && y1 >= 0 && y1 < h) ? load_value(base + y1 * w + x1) : 0.f;
  return (a * (1.f - dx) + b * dx) * (1.f - dy) +
         (c * (1.f - dx) + d * dx) * dy;
}

template <typename pred_t, typename target_t>
__launch_bounds__(256, 2)
__global__ void point_forward_kernel(const pred_t* __restrict__ pred, const target_t* __restrict__ target,
                                     const float* coords, float* bce, float* dice,
                                     float* sx, float* sy, float* num, float* den,
                                     int masks, int ph, int pw, int th, int tw,
                                     int points) {
  const int m = blockIdx.x;
  if (m >= masks) return;
  // A warp reduction removes the 4-way shared-memory atomic hot spot in the
  // old kernel.  There are at most eight warps for the launch below.
  constexpr int kWarps = 8;
  __shared__ float warp_sums[4][kWarps];
  const int tid = threadIdx.x;
  const int lane = tid & 31;
  const int warp = tid >> 5;
  float local[4] = {0.f, 0.f, 0.f, 0.f};
  const pred_t* p = pred + m * ph * pw;
  const target_t* t = target + m * th * tw;
  const float2* coords2 = reinterpret_cast<const float2*>(coords);
  for (int j = tid; j < points; j += blockDim.x) {
    // coords is contiguous N x P x 2, hence every pair is naturally
    // 8-byte aligned and is loaded as one vector transaction.
    const float2 xy = coords2[m * points + j];
    const float xcoord = xy.x;
    const float ycoord = xy.y;
    const float x = bilinear(p, ph, pw, xcoord, ycoord);
    const float y = bilinear(t, th, tw, xcoord, ycoord);
    sx[m * points + j] = x;
    sy[m * points + j] = y;
    const float prob = 1.f / (1.f + __expf(-x));
    const float loss = fmaxf(x, 0.f) + log1pf(__expf(-fabsf(x))) - x * y;
    local[0] += loss;
    local[1] += prob * y;
    local[2] += prob;
    local[3] += y;
  }
  #pragma unroll
  for (int r = 16; r > 0; r >>= 1) {
    local[0] += __shfl_down_sync(0xffffffff, local[0], r);
    local[1] += __shfl_down_sync(0xffffffff, local[1], r);
    local[2] += __shfl_down_sync(0xffffffff, local[2], r);
    local[3] += __shfl_down_sync(0xffffffff, local[3], r);
  }
  if (lane == 0) {
    warp_sums[0][warp] = local[0];
    warp_sums[1][warp] = local[1];
    warp_sums[2][warp] = local[2];
    warp_sums[3][warp] = local[3];
  }
  __syncthreads();
  if (tid == 0) {
    float sums[4] = {0.f, 0.f, 0.f, 0.f};
    const int nw = (blockDim.x + 31) >> 5;
    for (int w = 0; w < nw; ++w) {
      sums[0] += warp_sums[0][w]; sums[1] += warp_sums[1][w];
      sums[2] += warp_sums[2][w]; sums[3] += warp_sums[3][w];
    }
    bce[m] = sums[0] / static_cast<float>(points);
    const float n = 2.f * sums[1] + 1.f;
    const float d = sums[2] + sums[3] + 1.f;
    dice[m] = 1.f - n / d;
    num[m] = n;
    den[m] = d;
  }
}

__launch_bounds__(256, 2)
__global__ void point_backward_kernel(const float* __restrict__ coords, const float* __restrict__ sx,
                                      const float* sy, const float* num,
                                      const float* den, const float* gb,
                                      const float* gd, float* grad, int masks,
                                      int ph, int pw, int points) {
  const int m = blockIdx.x;
  if (m >= masks) return;
  extern __shared__ float shgrad[];
  const int pixels = ph * pw;
  // A per-mask shared gradient turns four contended global atomics per point
  // into fast shared atomics followed by one coalesced global store.  The
  // host enables this path only when the shape fits the SM120 dynamic shared
  // memory limit; larger maps use the global fallback below.
  for (int i = threadIdx.x; i < pixels; i += blockDim.x) shgrad[i] = 0.f;
  __syncthreads();
  const float n = num[m], d = den[m];
  for (int j = threadIdx.x; j < points; j += blockDim.x) {
    const float px = coords[(m * points + j) * 2];
    const float py = coords[(m * points + j) * 2 + 1];
    const float x = sx[m * points + j], y = sy[m * points + j];
    const float p = 1.f / (1.f + __expf(-x));
    const float gx = gb[m] * (p - y) / points +
        gd[m] * p * (1.f - p) * (n - 2.f * y * d) / (d * d);
    const float fx = px * pw - .5f, fy = py * ph - .5f;
    const int x0 = floorf(fx), y0 = floorf(fy), x1 = x0 + 1, y1 = y0 + 1;
    const float dx = fx - x0, dy = fy - y0;
    float* out = grad + m * ph * pw;
    if (x0 >= 0 && x0 < pw && y0 >= 0 && y0 < ph)
      atomicAdd(shgrad + y0 * pw + x0, gx * (1.f-dx) * (1.f-dy));
    if (x1 >= 0 && x1 < pw && y0 >= 0 && y0 < ph)
      atomicAdd(shgrad + y0 * pw + x1, gx * dx * (1.f-dy));
    if (x0 >= 0 && x0 < pw && y1 >= 0 && y1 < ph)
      atomicAdd(shgrad + y1 * pw + x0, gx * (1.f-dx) * dy);
    if (x1 >= 0 && x1 < pw && y1 >= 0 && y1 < ph)
      atomicAdd(shgrad + y1 * pw + x1, gx * dx * dy);
  }
  __syncthreads();
  for (int i = threadIdx.x; i < pixels; i += blockDim.x)
    grad[m * pixels + i] = shgrad[i];
}

__launch_bounds__(256, 2)
__global__ void point_backward_global_kernel(const float* __restrict__ coords, const float* __restrict__ sx,
                                      const float* sy, const float* num,
                                      const float* den, const float* gb,
                                      const float* gd, float* grad, int masks,
                                      int ph, int pw, int points) {
  const int m = blockIdx.x;
  if (m >= masks) return;
  const float n = num[m], d = den[m];
  for (int j = threadIdx.x; j < points; j += blockDim.x) {
    const float px = coords[(m * points + j) * 2];
    const float py = coords[(m * points + j) * 2 + 1];
    const float x = sx[m * points + j], y = sy[m * points + j];
    const float p = 1.f / (1.f + __expf(-x));
    const float gx = gb[m] * (p - y) / points +
        gd[m] * p * (1.f - p) * (n - 2.f * y * d) / (d * d);
    const float fx = px * pw - .5f, fy = py * ph - .5f;
    const int x0 = floorf(fx), y0 = floorf(fy), x1 = x0 + 1, y1 = y0 + 1;
    const float dx = fx - x0, dy = fy - y0;
    float* out = grad + m * ph * pw;
    if (x0 >= 0 && x0 < pw && y0 >= 0 && y0 < ph) atomicAdd(out + y0 * pw + x0, gx * (1.f-dx) * (1.f-dy));
    if (x1 >= 0 && x1 < pw && y0 >= 0 && y0 < ph) atomicAdd(out + y0 * pw + x1, gx * dx * (1.f-dy));
    if (x0 >= 0 && x0 < pw && y1 >= 0 && y1 < ph) atomicAdd(out + y1 * pw + x0, gx * (1.f-dx) * dy);
    if (x1 >= 0 && x1 < pw && y1 >= 0 && y1 < ph) atomicAdd(out + y1 * pw + x1, gx * dx * dy);
  }
}

// One warp handles one cost problem.  Each lane scans a disjoint set of
// queries and keeps the best T candidates in registers.  Lane 0 merges the
// 32 small lists in shared memory and enumerates T^T assignments.  This keeps
// the exact T<=4 behavior while replacing the serial Q loop in the original
// implementation with coalesced warp loads.
__launch_bounds__(32, 8)
__global__ void matcher_kernel(const float* __restrict__ cost, const bool* __restrict__ valid, int64_t* __restrict__ out,
                               int problems, int queries, int targets) {
  const int s = blockIdx.x;
  if (s >= problems) return;
  const int lane = threadIdx.x & 31;
  __shared__ int local_q[32 * 4 * 4];
  __shared__ float local_v[32 * 4 * 4];
  float best_v[4][4];
  int best_q[4][4];
  #pragma unroll
  for (int t = 0; t < 4; ++t) {
    #pragma unroll
    for (int k = 0; k < 4; ++k) { best_q[t][k] = -1; best_v[t][k] = INFINITY; }
  }
  for (int q = lane; q < queries; q += 32) {
    for (int t = 0; t < targets; ++t) {
      if (!valid[s * targets + t]) continue;
      const float v = cost[(s * queries + q) * targets + t];
      int pos = targets;
      #pragma unroll
      for (int k = 0; k < 4; ++k) if (k < targets && v < best_v[t][k]) { pos = k; break; }
      if (pos < targets) {
        for (int k = 3; k > 0; --k) if (k >= pos && k < targets) { best_v[t][k] = best_v[t][k-1]; best_q[t][k] = best_q[t][k-1]; }
        best_v[t][pos] = v; best_q[t][pos] = q;
      }
    }
  }
  for (int t = 0; t < targets; ++t) for (int k = 0; k < targets; ++k) {
    local_q[lane * 16 + t * 4 + k] = best_q[t][k];
    local_v[lane * 16 + t * 4 + k] = best_v[t][k];
  }
  __syncthreads();
  if (lane != 0) return;
  int cand[4][4];
  float cand_cost[4][4];
  for (int t = 0; t < targets; ++t) {
    for (int k = 0; k < targets; ++k) { cand[t][k] = -1; cand_cost[t][k] = INFINITY; }
    if (!valid[s * targets + t]) continue;
    for (int lane_i = 0; lane_i < 32; ++lane_i) {
      for (int k = 0; k < targets; ++k) {
        float v = local_v[lane_i * 16 + t * 4 + k];
        int q = local_q[lane_i * 16 + t * 4 + k];
        int pos = targets;
        for (int z = 0; z < targets; ++z) if (v < cand_cost[t][z]) { pos = z; break; }
        if (pos < targets) {
          for (int z = targets - 1; z > pos; --z) { cand_cost[t][z] = cand_cost[t][z-1]; cand[t][z] = cand[t][z-1]; }
          cand_cost[t][pos] = v; cand[t][pos] = q;
        }
      }
    }
  }
  for (int t = 0; t < targets; ++t) out[s * targets + t] = -1;
  float best = INFINITY;
  const int total = (targets == 1 ? 1 : targets == 2 ? 4 : targets == 3 ? 27 : 256);
  for (int code = 0; code < total; ++code) {
    int z = code; int chosen[4]; bool duplicate = false; float score = 0.f;
    for (int t = 0; t < targets; ++t) {
      int k = z % targets; z /= targets; chosen[t] = cand[t][k];
      if (valid[s * targets + t]) {
        if (chosen[t] < 0) { duplicate = true; break; }
        score += cand_cost[t][k];
        for (int u = 0; u < t; ++u) if (valid[s * targets + u] && chosen[u] == chosen[t]) duplicate = true;
      }
    }
    if (!duplicate && score < best) { best = score; for (int t = 0; t < targets; ++t) if (valid[s*targets+t]) out[s*targets+t] = chosen[t]; }
  }
}

